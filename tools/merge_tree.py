#!/usr/bin/env python3
"""Merge an extracted update RomFS tree over the base RomFS tree, then write a manifest.

Usage: merge_tree.py --base build/extracted/v0/romfs-tree --update ../../ns/010095B01AF94000/RomFs
                     --out build/extracted/latest --exefs-out build/extracted/latest/exefs
                     --base-exefs build/extracted/v0/exefs --update-exefs ../../ns/010095B01AF94000/ExeFs
                     --manifest data/expected-latest.json --version latest
"""
import argparse, hashlib, json, shutil
from pathlib import Path


def sha256(p):
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def copy_tree(src, dst):
    dst.mkdir(parents=True, exist_ok=True)
    for p in sorted(src.rglob('*')):
        if p.is_file():
            q = dst / p.relative_to(src)
            q.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(p, q)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--base', type=Path, required=True)
    ap.add_argument('--update', type=Path, required=True)
    ap.add_argument('--out', type=Path, required=True)
    ap.add_argument('--base-exefs', type=Path, required=True)
    ap.add_argument('--update-exefs', type=Path, required=True)
    ap.add_argument('--manifest', type=Path, required=True)
    a = ap.parse_args()

    if a.out.exists():
        shutil.rmtree(a.out)
    romfs = a.out / 'romfs'
    print(f'copying base RomFS {a.base} -> {romfs}', flush=True)
    copy_tree(a.base, romfs)

    replaced = []
    for p in sorted(a.update.rglob('*')):
        if not p.is_file():
            continue
        rel = p.relative_to(a.update)
        q = romfs / rel
        q.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, q)
        replaced.append(rel.as_posix())
    print(f'overlaid {len(replaced)} update files', flush=True)

    exefs = a.out / 'exefs'
    exefs.mkdir(parents=True, exist_ok=True)
    for p in sorted(a.base_exefs.iterdir()):
        if p.is_file():
            shutil.copy2(p, exefs / p.name)
    for p in sorted(a.update_exefs.iterdir()):
        if p.is_file():
            shutil.copy2(p, exefs / p.name)
    print(f'exefs: {sorted(x.name for x in exefs.iterdir() if x.is_file())}', flush=True)

    files = []
    for p in sorted(romfs.rglob('*')):
        if p.is_file():
            rel = p.relative_to(romfs).as_posix()
            files.append({'path': rel, 'size': p.stat().st_size, 'sha256': sha256(p),
                          'from': 'update' if rel in replaced else 'base'})
    total = sum(f['size'] for f in files)
    manifest = {
        'version': 0,
        'display_version': 'update (unknown version)',
        'note': 'Generated by tools/merge_tree.py from the base XCI and the update RomFS tree. Hashes are of the merged result.',
        'exefs_sha256': {p.name: sha256(p) for p in sorted(exefs.iterdir()) if p.is_file()},
        'romfs': {'size': total, 'sha256': None, 'file_count': len(files), 'files': files},
    }
    a.manifest.parent.mkdir(parents=True, exist_ok=True)
    a.manifest.write_text(json.dumps(manifest, indent=1))
    print(f'{len(files)} files, {total:,} bytes -> {a.manifest}', flush=True)


if __name__ == '__main__':
    main()
